// Generates src/data/scope3CfpTable.ts from public/EF_Scope3_V1.csv (the CFP / Scope 3 EF table).
// Run: node scripts/gen_scope3_cfp.cjs
const fs = require("fs");
const path = require("path");
const { readScope3Csv } = require("./parse_scope3_csv.cjs");

const rows = readScope3Csv();
const header = rows[0];
const idx = (name) => header.indexOf(name);
const iNo = idx("itemNo"), iItem = idx("item"), iUnit = idx("unit"), iEf = idx("ef"), iRef = idx("reference");

const clean = (s) => (s || "").replace(/\s+/g, " ").trim();
const entries = [];
for (const r of rows.slice(1)) {
  const ef = Number(r[iEf]);
  if (!r[iNo] || !r[iItem] || !Number.isFinite(ef)) continue;
  entries.push({
    no: Number(r[iNo]),
    name: clean(r[iItem]),
    unit: clean(r[iUnit]) || "unit",
    factor: ef,
    reference: clean(r[iRef]),
  });
}

const lines = entries.map(
  (e) => `  [${e.no}, ${JSON.stringify(e.name)}, ${JSON.stringify(e.unit)}, ${e.factor}, ${JSON.stringify(e.reference)}],`
);

const out = `// AUTO-GENERATED by scripts/gen_scope3_cfp.cjs from public/EF_Scope3_V1.csv. Do not edit by hand.
// Tuple: [itemNo, item, unit, ef (kgCO2e per unit), reference]
export const SCOPE3_CFP_TABLE: [number, string, string, number, string][] = [
${lines.join("\n")}
];
`;

const target = path.join(__dirname, "..", "src", "data", "scope3CfpTable.ts");
fs.writeFileSync(target, out, "utf8");
console.log("wrote", entries.length, "entries to", target);
